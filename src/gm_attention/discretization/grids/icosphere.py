def build_icosphere_grid(
    subdivisions: int,
    *,
    dtype: torch.dtype = torch.float64,
    device: torch.device | str | None = None,
) -> SphericalGrid:
    """Construct an icosphere grid on the unit sphere.

    Nodes are the vertices of a subdivided regular icosahedron projected
    onto the unit sphere, generated by ``trimesh.creation.icosphere``.
    Quadrature weights are barycentric dual-cell areas: each face
    contributes a third of its (exact, curved-triangle) area to each of its
    three vertices, then the weights are rescaled to sum exactly to
    ``4 * pi`` -- flat-triangle face areas slightly underestimate the true
    curved surface area.

    Parameters
    ----------
    subdivisions
        Number of icosahedron subdivisions; the face count grows as
        ``4 ** subdivisions``.
    dtype
        Floating-point dtype of the returned grid.
    device
        Device of the returned grid.

    Returns
    -------
    SphericalGrid
        Grid whose node count is determined by ``subdivisions``.
    """
    if subdivisions < 0:
        raise ValueError(
            f"subdivisions must be non-negative, got {subdivisions}."
        )

    mesh = trimesh.creation.icosphere(subdivisions=subdivisions, radius=1.0)

    vertices = np.asarray(mesh.vertices)  # (n_nodes, 3), numpy
    faces = np.asarray(mesh.faces)  # (n_faces, 3), numpy
    face_areas = np.asarray(mesh.area_faces)  # (n_faces,), numpy

    vertex_weights = np.zeros(vertices.shape[0], dtype=np.float64)  # (n_nodes,)
    np.add.at(
        vertex_weights,
        faces.ravel(),  # (n_faces * 3,)
        np.repeat(face_areas / 3.0, 3),  # (n_faces * 3,)
    )

    vertex_weights *= (4.0 * np.pi) / vertex_weights.sum()

    nodes = vertices / np.linalg.norm(  # (n_nodes, 3), numpy
        vertices,
        axis=-1,
        keepdims=True,
    )

    return SphericalGrid(
        nodes=torch.as_tensor(  # (n_nodes, 3)
            nodes,
            dtype=dtype,
            device=device,
        ).contiguous(),
        quadrature_weights=torch.as_tensor(  # (n_nodes,)
            vertex_weights,
            dtype=dtype,
            device=device,
        ).contiguous(),
        exact_nodes=torch.as_tensor(nodes, dtype=torch.float64),  # for edge membership
    )


@dataclass(frozen=True, slots=True)
class IcosphereRefinement:
    """How a level-``(k + 1)`` icosphere's nodes relate to level-``k``'s.

    ``trimesh``'s subdivision keeps every existing vertex at its index and
    appends the new midpoint vertices, so nodes ``0 .. n_coarse_nodes - 1``
    of the finer grid are exactly the coarser grid's nodes, in the same
    order; :func:`build_icosphere_refinement` verifies this. Each node
    ``n_coarse_nodes .. n_fine_nodes - 1`` is the sphere-projected midpoint
    of two coarse nodes, an edge of the coarser mesh, recorded in
    ``midpoint_parents`` in the coarse grid's index space.

    ``coarse_edge_length`` is the geodesic length (``arccos`` of the dot
    product of the unit endpoints) of one representative coarse-mesh edge;
    the edges of a subdivided icosahedron are close to equal in length
    except at the 12 valence-5 vertices, so it stands in for the coarse
    spacing when choosing an aggregation radius.
    """

    n_coarse_nodes: int
    midpoint_parents: Tensor  # (n_fine_nodes - n_coarse_nodes, 2) long
    coarse_edge_length: float


def build_icosphere_refinement(
    coarse_subdivisions: int,
    *,
    dtype: torch.dtype = torch.float64,
    device: torch.device | str | None = None,
) -> tuple[SphericalGrid, SphericalGrid, IcosphereRefinement]:
    """Build the icospheres at ``coarse_subdivisions`` and one level finer,
    with the :class:`IcosphereRefinement` relating them.

    Parameters
    ----------
    coarse_subdivisions
        Subdivision level of the coarser grid; the finer grid is
        ``coarse_subdivisions + 1``.
    dtype, device
        Passed to :func:`build_icosphere_grid` for both returned grids.

    Returns
    -------
    coarse_grid, fine_grid, refinement
    """
    if coarse_subdivisions < 0:
        raise ValueError(
            f"coarse_subdivisions must be non-negative, got {coarse_subdivisions}."
        )

    coarse_mesh = trimesh.creation.icosphere(subdivisions=coarse_subdivisions, radius=1.0)

    # The prefix check runs in float64 regardless of the requested dtype.
    coarse_grid_f64 = build_icosphere_grid(coarse_subdivisions, dtype=torch.float64)
    fine_grid_f64 = build_icosphere_grid(coarse_subdivisions + 1, dtype=torch.float64)

    n_coarse = coarse_grid_f64.n_nodes
    n_fine = fine_grid_f64.n_nodes

    # atol rather than torch.equal: independent icosphere() calls can differ
    # in the last bit of float64; 1e-10 is far above that noise floor.
    if not torch.allclose(coarse_grid_f64.nodes, fine_grid_f64.nodes[:n_coarse], atol=1e-10):
        raise RuntimeError(
            "Coarse icosphere nodes are not (nearly) an exact prefix of the "
            "fine icosphere's nodes. This function relies on trimesh's "
            "subdivision convention (existing vertices keep their index, "
            "new ones are appended) -- that convention may have changed in "
            "the installed trimesh version."
        )

    coarse_edges = np.asarray(coarse_mesh.edges_unique).copy()  # (n_coarse_edges, 2)

    if coarse_edges.shape[0] != n_fine - n_coarse:
        raise RuntimeError(
            f"Expected exactly {n_fine - n_coarse} new midpoint nodes (one "
            f"per coarse edge), got {coarse_edges.shape[0]} coarse edges."
        )

    coarse_edges_t = torch.as_tensor(coarse_edges, dtype=torch.long)
    coarse_positions = coarse_grid_f64.nodes[coarse_edges_t]  # (E, 2, 3)
    expected_midpoints = coarse_positions.mean(dim=1)
    expected_midpoints = expected_midpoints / torch.linalg.vector_norm(
        expected_midpoints, dim=-1, keepdim=True
    )

    fine_midpoints = fine_grid_f64.nodes[n_coarse:]  # (E, 3)

    # Nearest-neighbor match of each new fine node to its coarse edge: the
    # enumeration order of edges_unique need not match the insertion order.
    tree = cKDTree(expected_midpoints.numpy())
    matched_distance, matched_edge = tree.query(fine_midpoints.numpy(), k=1)

    tolerance = 1e-9
    if matched_distance.max() > tolerance:
        raise RuntimeError(
            "Nearest-neighbor match between fine midpoint nodes and coarse "
            f"edge midpoints was not exact (max distance "
            f"{matched_distance.max():.3e} > {tolerance:.0e}). trimesh's "
            "subdivision convention this function relies on may have "
            "changed in the installed version."
        )

    matched_edge_t = torch.as_tensor(matched_edge, dtype=torch.long)
    midpoint_parents = coarse_edges_t[matched_edge_t]  # (n_fine - n_coarse, 2)

    representative_endpoints = coarse_positions[0]  # (2, 3)
    coarse_edge_length = float(
        torch.arccos(
            torch.dot(representative_endpoints[0], representative_endpoints[1]).clamp(-1.0, 1.0)
        )
    )

    if dtype == torch.float64 and device is None:
        coarse_grid, fine_grid = coarse_grid_f64, fine_grid_f64
    else:
        coarse_grid = build_icosphere_grid(coarse_subdivisions, dtype=dtype, device=device)
        fine_grid = build_icosphere_grid(coarse_subdivisions + 1, dtype=dtype, device=device)

    return (
        coarse_grid,
        fine_grid,
        IcosphereRefinement(
            n_coarse_nodes=n_coarse,
            midpoint_parents=midpoint_parents.to(device=device),
            coarse_edge_length=coarse_edge_length,
        ),
    )


def build_icosphere_downsample_edges(
    fine_grid: SphericalGrid,
    fine_frames: Tensor,
    n_coarse_nodes: int,
    *,
    cutoff: float,
    max_frequency: int = DEFAULT_MAX_FREQUENCY,
) -> EdgeGeometry:
    """Bipartite fine-grid -> coarse-grid edges for :class:`~gm_attention.nn.blocks.IcoEncode`.

    The coarse nodes are the first ``n_coarse_nodes`` of ``fine_grid`` (see
    :class:`IcosphereRefinement`), so the edges are the fine grid's own edge
    geometry restricted to targets in that prefix, and
    ``tangent_quadrature_weights`` carry the fine (source) grid's
    quadrature: the aggregation approximates an integral over the fine
    grid's sampling density.

    Parameters
    ----------
    fine_grid, fine_frames
        The finer grid and its tangent frames.
    n_coarse_nodes
        The coarser grid's node count
        (:attr:`IcosphereRefinement.n_coarse_nodes`).
    cutoff
        Aggregation radius; :attr:`IcosphereRefinement.coarse_edge_length`
        (about twice the fine grid's spacing) covers the fine nodes around
        each coarse node.
    max_frequency
        Passed to :func:`~gm_attention.discretization.edge_geometry.compute_edge_geometry`.

    Returns
    -------
    EdgeGeometry
        ``row_ptr`` sized ``(n_coarse_nodes + 1,)``; ``source_index`` ranges
        over all of ``fine_grid``'s nodes.
    """
    if not (0 < n_coarse_nodes <= fine_grid.n_nodes):
        raise ValueError(
            "n_coarse_nodes must be in (0, fine_grid.n_nodes] = "
            f"(0, {fine_grid.n_nodes}], got {n_coarse_nodes}."
        )

    all_edges = compute_edge_geometry(
        fine_grid, fine_frames, coverage_radius=cutoff, max_frequency=max_frequency
    )
    target_in_coarse = all_edges.target_index < n_coarse_nodes  # (n_edges,) bool

    return all_edges.select(target_in_coarse, n_nodes=n_coarse_nodes)


def build_icosphere_upsample_edges(
    fine_grid: SphericalGrid,
    fine_frames: Tensor,
    refinement: IcosphereRefinement,
    *,
    max_frequency: int = DEFAULT_MAX_FREQUENCY,
) -> EdgeGeometry:
    """Parent-node edges for :class:`~gm_attention.nn.blocks.IcoDecode`'s upsample step.

    Each midpoint fine node receives exactly two directed edges, from its
    two coarse parents (:attr:`IcosphereRefinement.midpoint_parents`); the
    edge list is passed to
    :func:`~gm_attention.discretization.edge_geometry.edge_geometry_from_index`.

    Parameters
    ----------
    fine_grid, fine_frames
        The finer grid and its tangent frames.
    refinement
        From :func:`build_icosphere_refinement`.
    max_frequency
        Passed to ``edge_geometry_from_index``.

    Returns
    -------
    EdgeGeometry
        ``row_ptr`` sized ``(fine_grid.n_nodes + 1,)``; the first
        ``refinement.n_coarse_nodes`` rows have no incident edges.
    """
    n_coarse = refinement.n_coarse_nodes
    n_midpoints = refinement.midpoint_parents.shape[0]

    midpoint_index = torch.arange(  # (n_midpoints,)
        n_coarse, n_coarse + n_midpoints, dtype=torch.long, device=fine_grid.device
    )
    target_index = midpoint_index.repeat_interleave(2)  # (2 * n_midpoints,)
    source_index = refinement.midpoint_parents.reshape(-1)  # (2 * n_midpoints,)
    edge_index = torch.stack((target_index, source_index), dim=0)  # (2, 2 * n_midpoints)

    return edge_geometry_from_index(
        nodes=fine_grid.nodes,
        frames=fine_frames,
        spherical_quadrature_weights=fine_grid.quadrature_weights,
        edge_index=edge_index,
        n_target_nodes=fine_grid.n_nodes,
        max_frequency=max_frequency,
    )


@dataclass(frozen=True, slots=True)
class IcosphereHop:
    """One adjacent fine/coarse pair of an :class:`IcosphereMultiresolution`.

    ``down_edges`` is built at ``refinement.coarse_edge_length`` unless
    :func:`build_icosphere_multiresolution` is given ``down_cutoffs``;
    ``local_cutoffs`` does not affect it.
    """

    refinement: IcosphereRefinement
    down_edges: EdgeGeometry  # this hop's fine level -> coarse level; for nn.blocks.IcoEncode
    up_edges: EdgeGeometry  # coarse level -> fine midpoints; for nn.blocks.IcoDecode


@dataclass(frozen=True, slots=True)
class IcosphereMultiresolution:
    """A chain of ``depth + 1`` icosphere levels, one subdivision level
    apart, with the transfers :class:`~gm_attention.nn.blocks.IcoEncode`
    and ``IcoDecode`` need between adjacent levels.

    ``levels[0]`` is the finest and ``levels[-1]`` the coarsest; ``hops[k]``
    relates ``levels[k]`` (finer) to ``levels[k + 1]`` (coarser). Built once
    by :func:`build_icosphere_multiresolution`.
    """

    levels: tuple[SphericalDiscretization, ...]
    hops: tuple[IcosphereHop, ...]

    @property
    def depth(self) -> int:
        return len(self.hops)

    @property
    def finest(self) -> SphericalDiscretization:
        return self.levels[0]

    @property
    def coarsest(self) -> SphericalDiscretization:
        return self.levels[-1]


def build_icosphere_multiresolution(
    finest_subdivisions: int,
    depth: int,
    *,
    coarsest_cutoff: float,
    local_cutoffs: Mapping[int, float] | None = None,
    down_cutoffs: Mapping[int, float] | None = None,
    finest_frames: Tensor | None = None,
    max_frequency: int = DEFAULT_MAX_FREQUENCY,
    dtype: torch.dtype = torch.float64,
    device: torch.device | str | None = None,
) -> IcosphereMultiresolution:
    """Build a chain of ``depth + 1`` icosphere levels, one subdivision level
    apart, with the transfers between adjacent levels.

    Parameters
    ----------
    finest_subdivisions
        Subdivision level of ``levels[0]``; level ``k`` has subdivision
        level ``finest_subdivisions - k``.
    depth
        Number of refinement steps: ``levels`` has ``depth + 1`` entries and
        ``hops`` has ``depth``.
    coarsest_cutoff
        Support radius of the single-grid operators on ``levels[-1]``.
    down_cutoffs
        Optional sparse per-hop override ``{hop_index: cutoff}`` of the
        fine -> coarse aggregation radius, which otherwise is the hop's
        ``coarse_edge_length``. Used to evaluate a model at a resolution
        other than the one it was fitted at: the radius then belongs to the
        weights rather than to the mesh.
    local_cutoffs
        Optional sparse per-level override ``{level_index: cutoff}`` with
        keys in ``range(depth)``; the coarsest level's cutoff is always
        ``coarsest_cutoff``. A level not listed uses its own hop's
        ``coarse_edge_length``. This sets only that level's
        :class:`~gm_attention.discretization.discretization.SphericalDiscretization`
        and never ``hops[level_index].down_edges``.
    finest_frames
        Optional tangent frames for the finest level, shape
        ``(n_finest, 3, 2)``; built by
        :func:`~gm_attention.discretization.frames.build_tangent_frames`
        when omitted. Every coarser level's frames are the
        ``n_coarse_nodes`` prefix of this tensor.
    max_frequency
        Passed to every edge-geometry computation.
    dtype, device
        Passed to every :func:`build_icosphere_refinement` call.

    Returns
    -------
    IcosphereMultiresolution
    """
    if depth < 1:
        raise ValueError(f"depth must be at least 1, got {depth}.")

    if local_cutoffs is None:
        local_cutoffs = {}

    invalid_keys = set(local_cutoffs) - set(range(depth))
    if invalid_keys:
        raise ValueError(
            f"local_cutoffs keys must be in range(depth) = range({depth}) "
            "(the coarsest level's cutoff is set via coarsest_cutoff, not "
            f"local_cutoffs), got invalid keys {sorted(invalid_keys)}."
        )

    grids: list[SphericalGrid] = []
    refinements: list[IcosphereRefinement] = []

    for step in range(depth):
        coarse_grid, fine_grid, refinement = build_icosphere_refinement(
            finest_subdivisions - step - 1, dtype=dtype, device=device
        )

        if step == 0:
            grids.append(fine_grid)
        elif not torch.allclose(grids[step].nodes, fine_grid.nodes, atol=1e-10):
            # `fine_grid` independently rebuilds the level the previous step
            # produced as `coarse_grid`; a mismatch beyond one-ULP noise is an error.
            raise RuntimeError(
                f"Independently rebuilt level {step} does not match the "
                "canonical grid produced by the previous refinement step."
            )

        grids.append(coarse_grid)
        refinements.append(refinement)

    if finest_frames is None:
        finest_frames = build_tangent_frames(grids[0].nodes)

    resolved_down_cutoffs = {
        k: float(refinements[k].coarse_edge_length) for k in range(depth)
    }
    if down_cutoffs is not None:
        for index, cutoff in down_cutoffs.items():
            if not 0 <= index < depth:
                raise ValueError(
                    f"down_cutoffs index {index} is outside range(depth) for "
                    f"depth {depth}."
                )
            if not cutoff > 0.0:
                raise ValueError(
                    f"down_cutoffs[{index}] must be positive, got {cutoff}."
                )
            resolved_down_cutoffs[index] = float(cutoff)

    hops: list[IcosphereHop] = []
    for k in range(depth):
        fine_frames_k = finest_frames[: grids[k].n_nodes]
        down_edges = build_icosphere_downsample_edges(
            grids[k], fine_frames_k, refinements[k].n_coarse_nodes,
            cutoff=resolved_down_cutoffs[k], max_frequency=max_frequency,
        )
        up_edges = build_icosphere_upsample_edges(
            grids[k], fine_frames_k, refinements[k], max_frequency=max_frequency
        )
        hops.append(
            IcosphereHop(refinement=refinements[k], down_edges=down_edges, up_edges=up_edges)
        )

    levels: list[SphericalDiscretization] = []
    for k in range(depth + 1):
        frames_k = finest_frames[: grids[k].n_nodes]
        default_cutoff = coarsest_cutoff if k == depth else refinements[k].coarse_edge_length
        cutoff = local_cutoffs.get(k, default_cutoff)

        discretization = SphericalDiscretization.from_grid(
            grids[k], coverage_radius=cutoff, frames=frames_k, max_frequency=max_frequency
        )
        discretization.prepare_windows([cutoff])
        levels.append(discretization)

    return IcosphereMultiresolution(levels=tuple(levels), hops=tuple(hops))
